import assert from "node:assert/strict";
import {createPlanningPendingStore} from "../../apps/web_gui/eom_web_gui/static/content-planning-pending.js";
const values = new Map();
const storage = {getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key)};
const store = createPlanningPendingStore(storage);
const operation = {path: "commands", key: "studio:excel:12345678-1234-1234-1234-123456789abc", body: {command_kind: "EDIT_EDITION", edition_id: "edition_" + "1".repeat(32), edit: {change_kind: "SAVE_SECTIONS", changes: []}}};
store.write("first", operation);
assert.deepEqual(store.read("first"), operation);
assert.equal(store.read("second"), null);
assert.equal(store.read(null), null);
store.clear("first", {...operation, key: "studio:excel:99999999-1234-1234-1234-123456789abc"});
assert.deepEqual(store.read("first"), operation, "stale response removed newer request");
assert.throws(() => store.write("first", {...operation, path: "../accounts"}));
assert.throws(() => store.write("first", {...operation, csrf_token: "must-not-be-stored"}));
assert.throws(() => store.write("first", {...operation, body: {command_kind: "EDIT_EDITION", note: "x".repeat(4 * 1024 * 1024)}}));
const oversizedKorean = {...operation, body: {...operation.body, note: "가".repeat(1500000)}};
assert.ok(JSON.stringify(oversizedKorean).length < 4 * 1024 * 1024);
assert.throws(() => store.write("first", oversizedKorean), /너무 큽니다/);
assert.throws(() => createPlanningPendingStore({getItem: () => JSON.stringify(oversizedKorean)}).read("first"), /너무 큽니다/);
assert.deepEqual(store.read("first"), operation, "rejected envelope overwrote prior request");
store.clear("first", operation);
assert.equal(store.read("first"), null);
const archive = {...operation, path: "lifecycle", body: {action_kind: "CHANGE_LIFECYCLE", desired_state: "ARCHIVED"}};
store.write("first", archive);
assert.deepEqual(store.read("first"), archive);
store.clear("first", archive);
const failing = createPlanningPendingStore({setItem() {throw new Error("quota");}});
assert.throws(() => failing.write("first", operation), /quota/);
assert.throws(() => store.write(null, operation), /로그인/);
values.set("eom:excel:pending:1:first", "{}");
assert.throws(() => store.read("first"), /안전하게/);
console.log("content_planning_pending=PASS");
