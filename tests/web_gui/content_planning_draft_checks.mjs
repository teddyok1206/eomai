import assert from "node:assert/strict";
import {webcrypto} from "node:crypto";
import {createPlanningDraft, initialSections, slotSelection, targetIdentity} from "../../apps/web_gui/eom_web_gui/static/content-planning-draft.js";
globalThis.crypto ||= webcrypto;
const target = {placement_kind: "EXTERNAL_SOURCE_DOCUMENT", source_id: "extitem_" + "1".repeat(32), source_revision_id: "extitemrev_" + "2".repeat(32), observation_sha256: "sha256:" + "3".repeat(64), edition: 3, source_format: "HWPX"};
const sections = initialSections(2).map((s, i) => ({...s, form: {assembly_revision_id: `assemblyrev_${String(i).repeat(32)}`, manifest_sha256: "sha256:" + "a".repeat(64)}}));
const composition = {edition_id: "edition_" + "1".repeat(32), deliverable_revision_id: "delivrev_" + "2".repeat(32), composition_sha256: "sha256:" + "a".repeat(64), sections};
const draft = createPlanningDraft(), a = sections[0].section_id, b = sections[1].section_id;
draft.reset(composition); draft.load(a, []); draft.load(b, []);
assert.equal(draft.command(), null);
const p = draft.add(a, target), q = draft.add(a, target);
assert.notEqual(p, q);
assert.equal(draft.duplicateCounts(a).get(targetIdentity(target)), 2);
draft.move(a, p, b, 0);
assert.equal(draft.rows(a)[0].placement_id, q);
assert.equal(draft.rows(b)[0].placement_id, p);
assert.deepEqual(draft.command().edit.changes.map(row => row.placements.length), [1, 1]);
draft.update(b, p, {display_number: "가", points_milli: 2500, note: "메모", placement_id: "spoof"});
assert.equal(draft.rows(b)[0].placement_id, p);
assert.equal(draft.rows(b)[0].points_milli, 2500);
assert.throws(() => draft.load(b, []), /저장하지/);
assert.equal(draft.remove(a, "missing"), false);
assert.deepEqual(slotSelection({...target, external_number: "10321", document_artifact: {secret: "not_a_selection"}}), target);
draft.remove(a, q);
for (let i = 0; i < 1200; i++) draft.add(a, target);
const rows = draft.command().edit.changes[0].placements;
assert.equal(rows.length, 1200);
assert.equal(rows[1199].position, 1200);
assert.equal(new Set(rows.map(r => r.placement_id)).size, 1200);
const before = draft.rows(b);
assert.throws(() => draft.addMany(b, [target, null]), TypeError);
assert.deepEqual(draft.rows(b), before, "partial import altered the draft");
assert.throws(() => draft.addMany(b, []), /가져올/);
const imported = draft.addMany(b, [target, {...target, source_id: "extitem_" + "9".repeat(32)}, target]);
assert.equal(new Set(imported).size, 3);
assert.deepEqual(draft.rows(b).slice(-3).map(r => r.position), [2, 3, 4]);
assert.deepEqual(draft.rows(b).slice(-3).map(r => r.target.source_id), [target.source_id, "extitem_" + "9".repeat(32), target.source_id]);
assert.equal(draft.duplicateCounts(b).get(targetIdentity(target)), 3);
assert.throws(() => draft.addMany(b, Array(100000).fill(target)), /너무 많/);
assert.equal(draft.rows(b).length, 4, "over-budget import partially changed the draft");
const originalPositions = draft.rows(b).map(row => row.placement_id);
const inserted = draft.addMany(b, [target, target], 1);
assert.deepEqual(draft.rows(b).map(row => row.placement_id), [originalPositions[0], ...inserted, ...originalPositions.slice(1)]);
assert.deepEqual(draft.rows(b).map(row => row.position), [1, 2, 3, 4, 5, 6]);
assert.throws(() => draft.addMany(b, [target], -1), /삽입할 위치/);
assert.throws(() => draft.addMany(b, [target], 7), /삽입할 위치/);
draft.reset(); assert.equal(draft.dirty(), false); assert.equal(draft.loaded(a), false);
console.log("content_planning_draft=PASS");
